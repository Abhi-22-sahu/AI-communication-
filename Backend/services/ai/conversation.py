
import os
import logging

from Backend.services.ai.base import AIProvider
from Backend.services.ai.mock_provider import MockAIProvider
from Backend.services.ai.gemini_provider import GeminiProvider

logger = logging.getLogger(__name__)


def get_ai_provider() -> AIProvider:
    provider_name = os.getenv(
        "AI_PROVIDER", "mock"
    ).strip().lower()

    if provider_name == "gemini":
        return GeminiProvider()

    if provider_name == "mock":
        return MockAIProvider()

    raise ValueError(
        f"Unsupported AI provider: {provider_name}"
    )


def generate_response(
    conversation: list[dict],
    session_type: str,
    scenario: str
) -> str:
    provider = get_ai_provider()

    last_message = (
        conversation[-1] if conversation else {}
    )

    logger.warning(
        "AI provider selected: %s | "
        "Conversation messages: %d | "
        "Last role: %s | Session type: %s",
        type(provider).__name__,
        len(conversation),
        last_message.get("role", "none"),
        session_type
    )

    try:
        response = provider.generate_response(
            conversation=conversation,
            session_type=session_type,
            scenario=scenario
        )

        logger.warning(
            "AI response generated by %s: %s",
            type(provider).__name__,
            response[:200]
        )

        return response

    except Exception:
        logger.exception(
            "AI provider failed: %s",
            type(provider).__name__
        )
        logger.warning("Falling back to MockAIProvider.")

        fallback = MockAIProvider()

        return fallback.generate_response(
            conversation=conversation,
            session_type=session_type,
            scenario=scenario
        )
